"""Assemble the voice-over from one Kokoro clip per line (tools/vo-lines/<id>.wav).

Trims each clip's silence, places its first syllable at the line's `at`, writes
assets/audio/voiceover.wav (30 s, 48 kHz stereo, ~-16 LUFS) and assets/vo.js with
line and estimated word timings (captions + on-screen cues).
Usage: python3 tools/build_voice.py            (regenerate clips first: tools/make_voice.sh)
"""
import json, re, subprocess, wave
import numpy as np

SR = 48000
TOTAL = 30.0
cfg = json.load(open("tools/voice.json"))


def load(path):
    raw = subprocess.run(["ffmpeg", "-loglevel", "error", "-i", path, "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.float32).astype(np.float64)


def trim(x, thr_db=-42):
    win = int(0.01 * SR)
    n = len(x) // win
    rms = np.sqrt(np.mean(x[: n * win].reshape(n, win) ** 2, axis=1) + 1e-12)
    on = np.where(20 * np.log10(rms) > thr_db)[0]
    a, b = max(0, on[0] - 1) * win, min(n, on[-1] + 3) * win
    return x[a:b]


def weight(word):
    w = len(re.sub(r"[^\wÀ-ÿ]", "", word)) + 1.5
    return w


out = np.zeros(int(SR * TOTAL))
lines = []
for L in cfg["lines"]:
    x = trim(load(f"tools/vo-lines/{L['id']}.wav"))
    i = int(L["at"] * SR)
    out[i : i + len(x)] += x[: len(out) - i]
    start, end = L["at"], L["at"] + len(x) / SR
    words = L["text"].split()
    # pauses after ':' ',' '.' '?' '!' take time without letters
    ws = [weight(w) for w in words]
    gaps = [0.22 if re.search(r"[:,.?!]$", w) or (k + 1 < len(words) and words[k + 1] in ":?!") else 0.0 for k, w in enumerate(words)]
    dur = end - start - sum(gaps[:-1])
    tot = sum(ws)
    t = start
    wl = []
    for k, w in enumerate(words):
        d = dur * ws[k] / tot
        if w not in (":", "?", "!"):
            wl.append({"text": w, "start": round(t, 3), "end": round(t + d, 3)})
        else:
            wl[-1]["text"] += " " + w
        t += d + (gaps[k] if k < len(words) - 1 else 0)
    lines.append({"id": L["id"], "text": L["text"], "start": round(start, 3), "end": round(end, 3), "words": wl})

# loudness: simple RMS-gated normalisation to about -16 LUFS, true peak under -1 dBFS
speech = out[np.abs(out) > 1e-4]
rms = np.sqrt(np.mean(speech ** 2))
g = 10 ** (-17.5 / 20) / rms
out *= g
pk = np.max(np.abs(out))
if pk > 0.89:
    out *= 0.89 / pk
st = np.stack([out, out], 1)
with wave.open("assets/audio/voiceover.wav", "wb") as w:
    w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR)
    w.writeframes((st * 32767).astype(np.int16).tobytes())
open("assets/vo.js", "w").write("// generated by tools/build_voice.py\nwindow.VO = " + json.dumps(lines, ensure_ascii=False, indent=1) + ";\n")
for l in lines:
    print(l["id"], l["start"], l["end"])
