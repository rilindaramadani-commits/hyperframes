"""Word timings for the captions, aligned on the real voice-over clips.

For each plan clip (assets/audio/vo/pXX.wav) the speech envelope gives the pauses; punctuation
chunks of the script are snapped to those pauses, then words share each chunk by syllable count.
Writes assets/words.js (window.__WORDS) and tools/words.json. Run from the project root:
    python3 tools/align_words.py
"""
import json
import re
import wave

import numpy as np

timing = json.load(open("tools/timing.json"))
plan_json = {p["id"]: p for p in json.load(open("assets/plan.json"))["plans"]}
PLAN = timing["plan"]

VOWELS = "aeiouyàâäéèêëîïôöùûüœæ"


def syllables(word):
    core = re.sub(r"[^A-Za-z]", "", word)
    if core and core.isupper() and len(core) <= 4:
        return len(core)  # spelled acronyms: SPF, UV, C
    w = re.sub(r"[^a-zàâäéèêëîïôöùûüçœæ]", "", word.lower())
    if not w:
        return 1
    groups = re.findall(f"[{VOWELS}]+", w)
    n = len(groups)
    # silent final e / es / ent (rough French heuristic)
    if len(w) > 3 and re.search(r"(?<![aeiouy])e(s|nt)?$", w) and n > 1:
        n -= 1
    return max(1, n)


def envelope(path, hop=0.01):
    with wave.open(path) as f:
        sr = f.getframerate()
        x = np.frombuffer(f.readframes(f.getnframes()), dtype=np.int16).astype(np.float32) / 32768.0
        if f.getnchannels() > 1:
            x = x.reshape(-1, f.getnchannels()).mean(axis=1)
    n = int(sr * hop)
    frames = len(x) // n
    rms = np.sqrt(np.mean(x[: frames * n].reshape(frames, n) ** 2, axis=1) + 1e-12)
    db = 20 * np.log10(rms + 1e-9)
    return db, hop


def pauses(db, hop, start, end, thr):
    """Silent runs (>= 70 ms) strictly inside the speech span → list of (mid, length)."""
    out = []
    i0 = int(start / hop)
    i1 = int(end / hop)
    run = None
    for i in range(i0, i1):
        quiet = db[i] < thr
        if quiet and run is None:
            run = i
        elif not quiet and run is not None:
            if (i - run) * hop >= 0.07:
                out.append(((run + i) / 2 * hop, (i - run) * hop))
            run = None
    return out


words_out = []
for pid, p in PLAN.items():
    text = p["text"]
    lead = plan_json[pid]["lead"]
    clip_t0 = p["start"] + lead
    db, hop = envelope(f"assets/audio/vo/{pid}.wav")
    peak = float(np.max(db))
    thr = peak - 32
    s0 = p["voStart"] - clip_t0
    s1 = p["voEnd"] - clip_t0
    tokens = []
    for tok in text.split():
        if re.fullmatch(r"[:;!?…]+", tok) and tokens:
            tokens[-1] += "\u00a0" + tok  # French spacing: keep the mark with its word
        else:
            tokens.append(tok)
    syl = [syllables(t) for t in tokens]
    # chunk breaks after punctuation
    breaks = [i for i, t in enumerate(tokens[:-1]) if re.search(r"[,.:;…!?]$", t)]
    cands = pauses(db, hop, s0 + 0.05, s1 - 0.05, thr)
    total = sum(syl)
    chosen = []
    used = set()
    for b in breaks:
        expect = s0 + (s1 - s0) * sum(syl[: b + 1]) / total
        best = None
        for k, (mid, ln) in enumerate(cands):
            if k in used or (chosen and mid <= chosen[-1][0]):
                continue
            score = abs(mid - expect) - 0.6 * ln
            if best is None or score < best[0]:
                best = (score, k)
        if best is not None and abs(cands[best[1]][0] - expect) < 0.6:
            used.add(best[1])
            mid, ln = cands[best[1]]
            chosen.append((mid, ln, b))
    # build chunk spans
    spans = []
    cur_s = s0
    cur_i = 0
    for mid, ln, b in chosen:
        spans.append((cur_i, b, cur_s, mid - ln / 2))
        cur_i = b + 1
        cur_s = mid + ln / 2
    spans.append((cur_i, len(tokens) - 1, cur_s, s1))
    for i0, i1, a, e in spans:
        ss = syl[i0 : i1 + 1]
        tot = sum(ss)
        acc = 0
        for k, i in enumerate(range(i0, i1 + 1)):
            ws = a + (e - a) * acc / tot
            acc += ss[k]
            we = a + (e - a) * acc / tot
            words_out.append({"plan": pid, "w": tokens[i], "s": round(clip_t0 + ws, 3), "e": round(clip_t0 + we, 3)})

json.dump(words_out, open("tools/words.json", "w"), ensure_ascii=False, indent=1)
with open("assets/words.js", "w") as f:
    f.write("// Word timings (seconds) aligned on the voice-over — generated by tools/align_words.py. Do not edit by hand.\n")
    f.write("window.__WORDS = " + json.dumps(words_out, ensure_ascii=False) + ";\n")
print(len(words_out), "words")
for w in words_out:
    print(f'{w["plan"]} {w["s"]:6.2f} {w["e"]:6.2f} {w["w"]}')
