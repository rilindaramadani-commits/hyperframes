"""Builds assets/plan.js (shared timing for the 3D world, overlays and captions) from assets/plan.json.

Run from the project root: python3 tools/build_plan.py
"""
import json

plan = json.load(open("assets/plan.json"))
TEXT = {
    "p01": "Tu peux avoir les meilleurs produits du monde… et quand même saboter ta peau.",
    "p02": "Voici trois erreurs que je vois tout le temps.",
    "p03": "Erreur numéro un : trop de produits.",
    "p04": "Sérum, exfoliant, rétinol, vitamine C… tout, le même soir.",
    "p05": "Trop d'actifs à la fois, ça peut irriter ta peau, et fragiliser sa barrière.",
    "p06": "Garde l'essentiel. Et un actif à la fois.",
    "p07": "Erreur numéro deux : oublier le SPF.",
    "p08": "Nettoyant, sérum, crème… et tu sors. Il manque une étape.",
    "p09": "Les UV contribuent au vieillissement de la peau, et aux taches. Même quand il fait gris.",
    "p10": "Le SPF, c'est la dernière étape du matin. Tous les jours.",
    "p11": "Erreur numéro trois : changer de routine sans arrêt.",
    "p12": "Nouveau sérum lundi, nouveau nettoyant mercredi, nouvel exfoliant vendredi…",
    "p13": "Impossible de savoir ce qui marche vraiment. Ta peau a besoin de temps.",
    "p14": "Une routine simple, et quelques semaines de patience.",
    "p15": "Moins d'actifs. Du SPF chaque matin. De la régularité.",
    "p16": "Une bonne skincare, ce n'est pas d'en faire plus. C'est de faire les bonnes choses, régulièrement.",
    "p17": "Enregistre cette vidéo pour vérifier ta routine.",
}
meta = json.load(open("tools/vo_meta.json"))
P = {}
for p in plan["plans"]:
    m = meta[p["id"]]
    vs = p["start"] + p["lead"]
    P[p["id"]] = {
        "start": p["start"], "dur": p["dur"], "end": round(p["start"] + p["dur"], 3),
        "voStart": round(vs + m["speechStart"], 3), "voEnd": round(vs + m["speechEnd"], 3), "text": TEXT[p["id"]],
    }
s = lambda k: P[k]["start"]
CUE = {
    "d1In": round(s("p03") - 0.2, 3), "d1Out": round(s("p07") - 0.7, 3),
    "d2In": round(s("p07") + 0.15, 3), "d2Out": round(s("p11") - 0.7, 3),
    "d3In": round(s("p11") + 0.12, 3), "d3Out": round(s("p15") - 0.45, 3),
    "rw1": [round(s("p06") - 0.4, 3), s("p06")], "rw2": [round(s("p10") - 0.4, 3), s("p10")], "rw3": [round(s("p14") - 0.5, 3), s("p14")],
    "whip10": [round(s("p10") + 1.6, 3), round(s("p10") + 1.8, 3)],
    "days": [round(s("p12") + x, 3) for x in (0.75, 2.0, 3.15, 3.85)],
}
# second pass: once tools/align_words.py has run, beats that follow the voice use its word timings
try:
    words = json.load(open("tools/words.json"))
    W = lambda plan, pre: next((w for w in words if w["plan"] == plan and w["w"].lower().startswith(pre)), None)
    lun, mer, ven, tous = W("p12", "lundi"), W("p12", "mercredi"), W("p12", "vendredi"), W("p10", "tous")
    if lun and mer and ven:
        last = min(ven["e"] + 0.5, s("p13") - 0.95)
        CUE["days"] = [round(lun["s"], 3), round(mer["s"], 3), round(ven["s"], 3), round(max(last, ven["s"] + 0.7), 3)]
    if tous:
        CUE["whip10"] = [round(tous["s"] - 0.35, 3), round(tous["s"] - 0.15, 3)]
except FileNotFoundError:
    pass
with open("assets/plan.js", "w") as f:
    f.write("// Shared timing (seconds) — generated by tools/build_plan.py from assets/plan.json. Do not edit by hand.\n")
    f.write("window.__PLAN = " + json.dumps(P, ensure_ascii=False, indent=1) + ";\n")
    f.write("window.__CUE = " + json.dumps(CUE) + ";\n")
    f.write("window.__TOTAL = " + str(plan["total"]) + ";\n")
json.dump({"plan": P, "cue": CUE, "total": plan["total"]}, open("tools/timing.json", "w"), ensure_ascii=False, indent=1)
print(json.dumps(CUE))
