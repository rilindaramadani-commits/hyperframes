"""Sound-design cue sheet → the <audio> SFX block of index.html.

Every effect is placed from the plan timing (tools/timing.json) and the word timings
(tools/words.json), so a retime only needs this script re-run. Run from the project root:
    python3 tools/build_sfx.py
"""
import glob
import json
import wave

words = json.load(open("tools/words.json"))
tim = json.load(open("tools/timing.json"))
P, C = tim["plan"], tim["cue"]


def W(plan, prefix, fb):
    for w in words:
        if w["plan"] == plan and w["w"].lower().startswith(prefix.lower()):
            return w["s"]
    return fb


def T(pid, s=0):
    return P[pid]["start"] + s


dur = {}
for f in glob.glob("assets/audio/sfx-*.wav"):
    with wave.open(f) as w:
        dur[f.split("/")[-1][4:-4]] = round(w.getnframes() / w.getframerate(), 3)
ev = []


def A(t, n, v):
    ev.append((round(t, 3), n, v))


# P01–P02 hook and plinths
A(1.52, "drop", 0.55)
A(1.9, "whoosh", 0.36)
A(W("p01", "saboter", 2.88) - 0.03, "crack", 0.42)
for i, n in enumerate(["pop-1", "pop-2", "pop-3"]):
    A(T("p02", 0.15) + 0.12 * i, n, 0.42)
A(T("p02", 0.6), "tick", 0.3)
A(C["d1In"] - 0.45, "suck", 0.42)
# P03–P06 too many products
A(T("p03", 0.27), "impact", 0.42)
land = [W("p04", "Sérum", 8.63) + 0.12, W("p04", "exfoliant", 9.01) + 0.12, W("p04", "rétinol", 9.59) + 0.12, W("p04", "vitamine", 10.31) + 0.15, 10.95, 11.12, 11.3, 11.47, 11.64]
for t, n in zip(land, ["clink-1", "clink-1", "clink-2", "clink-2", "clink-3", "clink-3", "clink-4", "clink-4", "clink-4"]):
    A(t - 0.02, n, 0.3)
A(9.3, "gauge", 0.2)
A(11.72, "creak", 0.32)
A(T("p05", 0.05), "tink", 0.28)
A(T("p05", 0.3), "drips", 0.34)
A(W("p05", "fragiliser", 14.7), "crack", 0.38)
A(C["rw1"][0] - 0.07, "click", 0.5)
A(C["rw1"][0], "rewind", 0.45)
A(T("p06", 0.4), "shimmer", 0.26)
A(T("p06", 0.4), "pop-1", 0.3)
A(W("p06", "actif", 18.0) - 0.02, "pop-2", 0.4)
A(C["d1Out"] - 0.32, "whoosh", 0.36)
A(C["d1Out"] + 0.15, "check-1", 0.38)
A(C["d2In"] - 0.45, "suck", 0.4)
# P07–P10 forgetting SPF
A(T("p07", 0.33), "impact", 0.42)
A(20.2, "birds", 0.15)
for i, (pre, fb) in enumerate([("Nettoyant", 22.08), ("sérum", 22.52), ("crème", 22.96)]):
    A(W("p08", pre, fb) + 0.02, f"check-{i + 1}", 0.38)
A(T("p08", 1.3), "whoosh", 0.26)
A(T("p08", 1.8), "wind", 0.18)
A(W("p08", "manque", 24.11), "bonk", 0.42)
A(T("p09", 0.0), "uvpad", 0.2)
tac = W("p09", "taches", 27.96)
for k in range(4):
    A(tac - 0.28 + 0.15 * k, "tink", 0.26)
A(W("p09", "Même", 28.39) - 0.1, "wind", 0.22)
A(C["rw2"][0] - 0.07, "click", 0.5)
A(C["rw2"][0], "rewind", 0.45)
spf = W("p10", "SPF", 30.24) + 0.45
A(spf - 0.02, "pop-2", 0.38)
A(spf + 0.06, "chime", 0.24)
A(C["whip10"][0] - 0.08, "whoosh", 0.36)
A(C["whip10"][1] + 0.05, "film", 0.32)
A(C["whip10"][1] + 0.36, "ting", 0.28)
A(C["whip10"][1] + 0.55, "ting", 0.24)
A(C["d2Out"] - 0.32, "whoosh", 0.36)
A(C["d2Out"] + 0.15, "check-2", 0.38)
A(C["d3In"] - 0.45, "suck", 0.4)
# P11–P14 changing everything
A(T("p11", 0.33), "impact", 0.42)
A(T("p11", 0.5), "shimmer", 0.2)
A(36.4, "hats", 0.2)
for k, f in enumerate(C["days"]):
    A(f - 0.1, "page", 0.36)
    A(f + 0.53, ["pop-1", "pop-2", "pop-3", "pop-3"][k], 0.36)
    A(f + 0.62, "sandflip", 0.3)
A(T("p13", 0.05), "whoosh", 0.22)
for k, n in enumerate(["plop-1", "plop-2", "plop-3", "plop-1"]):
    A(T("p13", 0.7) + 0.15 * k, n, 0.36)
A(C["rw3"][0] - 0.07, "click", 0.5)
A(C["rw3"][0], "rewind", 0.45)
for k, n in enumerate(["pop-1", "pop-2", "pop-3"]):
    A(C["rw3"][1] + 0.05 + 0.12 * k, n, 0.24)
A(C["rw3"][1] + 0.1, "sand", 0.24)
q = W("p14", "quelques", 46.17)
for k in range(3):
    A(q - 0.1 + 0.3 * k, "page", 0.3)
A(q + 0.6, "shimmer", 0.2)
A(C["d3Out"] - 0.32, "whoosh", 0.36)
A(C["d3Out"] + 0.15, "check-3", 0.38)
# P15–P17 conclusion
for pre, fb, n in [("Moins", 48.23, "pop-1"), ("Du", 48.81, "pop-2"), ("De", 50.12, "pop-3")]:
    A(W("p15", pre, fb) - 0.05, n, 0.42)
A(W("p16", "régulièrement", 55.13) - 0.08, "shimmer", 0.24)
A(T("p17", 1.15), "click", 0.5)
A(T("p17", 1.2), "pop-3", 0.42)

ev.sort()
tracks, lines, count = [], [], {}
for t, n, v in ev:
    d = min(dur[n], round(59.5 - t, 3))
    tr = next((i for i, end in enumerate(tracks) if end <= t - 0.01), None)
    if tr is None:
        tracks.append(0)
        tr = len(tracks) - 1
    tracks[tr] = t + d
    count[n] = count.get(n, 0) + 1
    lines.append(f'      <audio id="sfx-{n}-{count[n]}" src="assets/audio/sfx-{n}.wav" data-start="{t}" data-duration="{d}" data-track-index="{30 + tr}" data-volume="{v}"></audio>')
block = "      <!-- SOUND DESIGN (generated by tools/build_sfx.py from plan.js + words.js) -->\n" + "\n".join(lines) + "\n"
s = open("index.html").read()
a = s.index("      <!-- SOUND DESIGN")
b = s.index("    </div>\n\n    <!-- ===================== ROOT TIMELINE")
open("index.html", "w").write(s[:a] + block + s[b:])
print(len(lines), "sfx on", len(tracks), "tracks")
